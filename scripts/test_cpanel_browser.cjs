const { chromium } = require('../.local/cpanel-test/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  const context = await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1366,height:900}});
  const page = await context.newPage();
  const problems=[];
  page.on('pageerror',e=>problems.push(e.message));
  const base='https://localhost:9443';
  await page.goto(base+'/ti/');
  await page.locator('input[name=username]').fill('cpanel-test');
  await page.locator('input[name=password]').fill('cpanel-test-password');
  await page.getByRole('button',{name:'Entrar no painel'}).click();
  await page.getByRole('heading',{name:'Olá, Teste cPanel'}).waitFor();
  const cookie=(await context.cookies()).find(c=>c.name==='givova_session');
  assert(cookie.httpOnly && cookie.secure && cookie.sameSite==='Strict');
  const create=await context.newPage();
  create.on('pageerror',e=>problems.push(e.message));
  await create.goto(base+'/chamado/');
  await create.locator('#requester-name').fill('Navegador cPanel');
  await create.locator('#requester-state').selectOption('SP');
  await create.locator('#requester-location').fill('Sala de teste');
  await create.locator('input[name=department][value=Financeiro]').check({force:true});
  await create.getByRole('button',{name:'Frete Brás',exact:true}).click();
  await create.locator('#problem-title').fill('Teste de interface Frete Brás');
  await create.locator('#problem-description').fill('Chamado descartável via Apache PHP');
  const ticketPromise=create.waitForResponse(r=>r.url().endsWith('/api/tickets') && r.request().method()==='POST');
  await create.getByRole('button',{name:'Chamar TI',exact:true}).click();
  const result=await (await ticketPromise).json();
  await create.waitForURL(/acompanhar/);
  assert(create.url().includes('#'+result.access_key));
  await create.getByRole('heading',{name:'Pronto! A TI recebeu seu pedido.'}).waitFor();
  await create.reload();
  await create.getByRole('heading',{name:'Pronto! A TI recebeu seu pedido.'}).waitFor();
  await create.goto(base+'/chamado/'+result.protocol+'#'+result.access_key);
  await create.getByRole('heading',{name:'Pronto! A TI recebeu seu pedido.'}).waitFor();
  assert(create.url().includes('/acompanhar/?protocol='+result.protocol+'#'+result.access_key));
  await page.getByText('Teste de interface Frete Brás',{exact:true}).first().waitFor({timeout:25000});
  assert((await page.locator('body').innerText()).includes('Novo chamado'));
  await page.screenshot({path:'.local/cpanel-validation/dashboard.png',fullPage:true});
  const jsonHeaders={'Origin':base,'Content-Type':'application/json'};
  let r=await context.request.post(base+'/api/tickets/'+result.id+'/assign',{headers:jsonHeaders});
  assert.equal(r.status(),200);
  await create.getByRole('heading',{name:'A TI está indo até você!'}).waitFor({timeout:25000});
  r=await context.request.post(base+'/api/tickets/'+result.id+'/resolve',{headers:jsonHeaders,data:{solution:'Resolvido pelo teste de navegador.'}});
  assert.equal(r.status(),200);
  await create.getByRole('heading',{name:'Tudo certo! Seu problema foi resolvido.'}).waitFor({timeout:25000});
  for (const route of ['/','/chamado/','/ti/','/tutorial/','/acompanhar/?protocol='+result.protocol+'#'+result.access_key]) {
    for (const width of [390,1366]) {
      await create.setViewportSize({width,height:844});
      await create.goto(base+route);
      await create.waitForTimeout(500);
      assert(await create.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth), 'horizontal overflow '+route+' '+width);
    }
  }
  await create.setViewportSize({width:390,height:844});
  await create.goto(base+'/chamado/');
  await create.locator('#requester-name').waitFor();
  await create.screenshot({path:'.local/cpanel-validation/mobile.png',fullPage:true});
  await create.goto(base+'/tutorial/');
  const video=create.locator('video');
  await video.waitFor();
  await create.waitForFunction(()=>document.querySelector('video').readyState>=1);
  assert(await video.evaluate(v=>v.duration>0 && !v.error));
  await page.getByRole('button',{name:'Sair',exact:true}).click();
  await page.getByRole('button',{name:'Entrar no painel'}).waitFor();
  assert.equal((await context.request.get(base+'/api/dashboard')).status(),401);
  assert.equal(problems.length,0,problems.join('\n'));
  fs.writeFileSync('.local/cpanel-validation/browser-results.json',JSON.stringify({login:true,cookies:true,creation:true,FreteBras:true,tracking:true,legacyFragment:true,reload:true,pollingNotifications:true,pollingAssignment:true,pollingResolution:true,responsiveWidths:[390,1366],video:true,logout:true,pageErrors:problems},null,2));
  console.log('PASS browser login, creation, tracking, notifications, polling, responsive layout, video, logout');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
